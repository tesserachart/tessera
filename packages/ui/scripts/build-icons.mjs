import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';
import { cut, cutPath, rectPath } from './icon-cuts.ts';

export const CUT_SIZES = [11, 12, 14, 16, 20];

const STROKE = {
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '1.5',
  'stroke-linecap': 'square',
  'stroke-linejoin': 'miter',
};

const root = join(import.meta.dirname, '..');
const svgFile = join(root, 'icons/icons.svg');
const jsFile = join(root, 'icons/icons.js');
const out = join(root, 'src/icons/glyphs.gen.ts');

const attrsOf = (s) => Object.fromEntries([...s.matchAll(/([A-Za-z-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
const unescape = (s) => s.replace(/&amp;/g, '&');

export function readGlyphs(svg) {
  const glyphs = {};
  const labels = {};
  for (const m of svg.matchAll(/<symbol ([^>]*)>([\s\S]*?)<\/symbol>/g)) {
    const attrs = attrsOf(m[1]);
    const name = attrs.id?.replace(/^i-/, '');
    if (!name || !/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`icons.svg: bad symbol id ${attrs.id}`);
    if (attrs.viewBox !== '0 0 20 20') throw new Error(`icons.svg: ${name} is not on the 20 px grid`);
    if (!attrs['data-label']) throw new Error(`icons.svg: ${name} has no data-label`);
    for (const [k, v] of Object.entries(STROKE)) {
      if (attrs[k] !== v) throw new Error(`icons.svg: ${name} must set ${k}="${v}"`);
    }
    const shapes = [];
    const rest = m[2].replace(/<(rect|path)\b([^>]*)\/>/g, (_, tag, raw) => {
      const a = attrsOf(raw);
      const fill = a.fill === 'currentColor' && a.stroke === 'none';
      if (!fill && (a.fill !== undefined || a.stroke !== undefined)) {
        throw new Error(`icons.svg: ${name} has a shape that is neither the stroke nor a fill`);
      }
      const d = tag === 'rect' ? rectPath([a.x, a.y, a.width, a.height].map(Number)) : a.d;
      shapes.push({ d, fill });
      return '';
    });
    if (rest.trim()) throw new Error(`icons.svg: ${name} holds something other than rect and path: ${rest.trim()}`);
    glyphs[name] = shapes;
    labels[name] = unescape(attrs['data-label']);
  }
  return { glyphs, labels };
}

function compiled(shapes) {
  return {
    stroke: shapes
      .filter((s) => !s.fill)
      .map((s) => s.d)
      .join(''),
    fills: shapes.filter((s) => s.fill).map((s) => s.d),
    cuts: Object.fromEntries(CUT_SIZES.map((size) => [size, cutPath(cut(shapes, size))])),
  };
}

function labSprite(svg) {
  const symbols = [...svg.matchAll(/<symbol[\s\S]*?<\/symbol>/g)].map((m) => m[0]).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">${symbols}</svg>`;
}

function syncedLab(js, svg, labels) {
  const names = Object.keys(labels);
  return js
    .replace(/^(\s*var SPRITE = ).*;$/m, (_, head) => `${head}${JSON.stringify(labSprite(svg))};`)
    .replace(
      /^(\s*window\.TesseraIcons = ).*;$/m,
      (_, head) =>
        `${head}{ names: ${JSON.stringify(names).replace(/","/g, '", "')}, labels: ${JSON.stringify(labels).replace(/","/g, '", "').replace(/":"/g, '": "')} };`,
    );
}

function generate() {
  const svg = readFileSync(svgFile, 'utf8');
  const js = readFileSync(jsFile, 'utf8');
  const { glyphs, labels } = readGlyphs(svg);
  const decl = js.split('\n').find((l) => /^\s*var PIX = /.test(l));
  if (!decl) throw new Error('icons.js: no PIX declaration');
  const mark = vm.runInNewContext(`${decl}\n({ PIX: PIX, PIX16: PIX16, VEC: VEC })`);
  const built = Object.fromEntries(Object.entries(glyphs).map(([n, s]) => [n, compiled(s)]));
  const ts = `// Generated by scripts/build-icons.mjs from icons/icons.svg and icons/icons.js (tessera-lab v5/system).
// Do not edit: change the sources and run \`bun run --filter @tessera/ui icons\`.

/** The pixel sizes that have a hand-snapped cut for 1x screens. */
export const ICON_CUT_SIZES = ${JSON.stringify(CUT_SIZES)} as const;

type IconCutSize = (typeof ICON_CUT_SIZES)[number];

/** An icon on the 20 px grid: its 1.5 px stroke, its solid fills, and its cut at each size, in that size's pixels. */
export interface Glyph {
  readonly stroke: string;
  readonly fills: readonly string[];
  readonly cuts: Readonly<Record<IconCutSize, string>>;
}

export type IconName = ${Object.keys(built)
    .map((n) => JSON.stringify(n))
    .join(' | ')};

export const GLYPHS: Record<IconName, Glyph> = ${JSON.stringify(built)};

/** The word each icon stands for (its tooltip and accessible name). */
export const ICON_LABELS: Record<IconName, string> = ${JSON.stringify(labels)};

/** The keyed T's pixel cuts at 20, 24 and 32: the human half \`h\`, the analyst's half \`a\` (rects with
 * coverage) and the seam column \`s\`, lit top to bottom. */
export const MARK_PIX: Record<'20' | '24' | '32', { h: number[][]; a: number[][]; s: number[][] }> = ${JSON.stringify(mark.PIX)};

/** The 16 px cut: no seam; at rest, or with the analyst's half one crossbar low. */
export const MARK_PIX16: { rest: number[][]; draft_h: number[][]; draft_a: number[][] } = ${JSON.stringify(mark.PIX16)};

/** The vector cut (48 and up), on a ${mark.VEC.w} × ${mark.VEC.hgt} box; \`drop\` is the draft's offset of the analyst's half. */
export const MARK_VEC: { w: number; hgt: number; h: string; a: string; seam: string; drop: number } = ${JSON.stringify(mark.VEC)};
`;
  return { ts, js: syncedLab(js, svg, labels), count: Object.keys(glyphs).length };
}

if (process.argv[1] === import.meta.filename) {
  const { ts, js, count } = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== ts || readFileSync(jsFile, 'utf8') !== js) {
      console.error('src/icons/glyphs.gen.ts or icons/icons.js is stale: run bun run --filter @tessera/ui icons');
      process.exit(1);
    }
  } else {
    writeFileSync(out, ts);
    writeFileSync(jsFile, js);
    console.info(`wrote ${out}: ${String(count)} icons`);
  }
}
