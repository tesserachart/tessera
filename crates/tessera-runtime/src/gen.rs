use std::collections::BTreeMap;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use tessera_host::{TsExports, check_declarations, tool_map_ts, topic_map_ts};
use ts_rs::{Config, ExportError};

#[derive(Debug, thiserror::Error)]
pub enum GenError {
    #[error("ts-rs export failed: {0}")]
    Export(#[from] ExportError),
    #[error(transparent)]
    Declarations(#[from] tessera_host::ts::DeclarationError),
    #[error("io error at {path}: {source}")]
    Io { path: PathBuf, source: io::Error },
}

fn io_err(path: &Path) -> impl FnOnce(io::Error) -> GenError + '_ {
    move |source| GenError::Io {
        path: path.to_owned(),
        source,
    }
}

pub fn default_out_dir() -> PathBuf {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let workspace = crate_dir
        .parent()
        .and_then(Path::parent)
        .unwrap_or(crate_dir);
    workspace.join("packages/protocol/src/gen")
}

fn export_into(dir: &Path, all: &[TsExports]) -> Result<(), GenError> {
    let cfg = Config::new().with_out_dir(dir);
    for e in all {
        e.export(&cfg)?;
    }
    Ok(())
}
const INDICATORS_TS: &str = "indicators.ts";

fn indicators_ts() -> String {
    let specs = serde_json::to_string_pretty(&tessera_protocol::indicators::indicator_specs())
        .unwrap_or_else(|_| "[]".into());
    let swatches = serde_json::to_string(&tessera_protocol::indicators::COLOR_SWATCHES)
        .unwrap_or_else(|_| "[]".into());
    format!(
        "// Generated by tessera-gen (crates/tessera-runtime). Do not edit.\n\
         // Regenerate with: bun run gen\n\
         import type {{ IndicatorSpec }} from \"./IndicatorSpec\";\n\n\
         /** Every indicator's declaration (crates/tessera-protocol/src/indicators.rs). */\n\
         export const INDICATOR_SPECS: readonly IndicatorSpec[] = {specs};\n\n\
         /** The palette swatches an indicator colour may name (or a custom #rrggbb). */\n\
         export const COLOR_SWATCHES: readonly string[] = {swatches};\n"
    )
}

const THEME_TS: &str = "theme.ts";

fn theme_ts() -> String {
    let tables = serde_json::to_string_pretty(&tessera_protocol::theme::tables_json())
        .unwrap_or_else(|_| "{}".into());
    format!(
        "// Generated by tessera-gen (crates/tessera-runtime). Do not edit.\n\
         // Regenerate with: bun run gen\n\n\
         /** The theme's tables: the app's colours, the chart's, the built-in themes and the chart looks \
         (crates/tessera-protocol/src/theme.rs, chart_theme.rs). */\n\
         export const THEME_TABLES = {tables} as const;\n"
    )
}

fn index_ts(files: &BTreeMap<String, String>) -> String {
    let mut out = String::from(
        "// Generated by tessera-gen (crates/tessera-runtime). Do not edit.\n\
         // Regenerate with: bun run gen\n",
    );
    let mut entries: Vec<(&str, &str)> = files
        .keys()
        .filter_map(|path| {
            let module = path.strip_suffix(".ts")?;
            let name = module.rsplit('/').next()?;
            (module != "index" && path != INDICATORS_TS && path != THEME_TS)
                .then_some((name, module))
        })
        .collect();
    entries.sort();
    for (name, module) in entries {
        out.push_str(&format!("export type {{ {name} }} from \"./{module}\";\n"));
    }
    if files.contains_key(INDICATORS_TS) {
        out.push_str("export { INDICATOR_SPECS, COLOR_SWATCHES } from \"./indicators\";\n");
    }
    if files.contains_key(THEME_TS) {
        out.push_str("export { THEME_TABLES } from \"./theme\";\n");
    }
    out
}

fn read_ts_files(dir: &Path) -> Result<BTreeMap<String, String>, GenError> {
    fn walk(base: &Path, dir: &Path, out: &mut BTreeMap<String, String>) -> Result<(), GenError> {
        for entry in fs::read_dir(dir).map_err(io_err(dir))? {
            let entry = entry.map_err(io_err(dir))?;
            let path = entry.path();
            if path.is_dir() {
                walk(base, &path, out)?;
            } else if path.extension().is_some_and(|e| e == "ts") {
                let rel = path
                    .strip_prefix(base)
                    .unwrap_or(&path)
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect::<Vec<_>>()
                    .join("/");
                let content = fs::read_to_string(&path).map_err(io_err(&path))?;
                out.insert(rel, content);
            }
        }
        Ok(())
    }
    let mut files = BTreeMap::new();
    if dir.exists() {
        walk(dir, dir, &mut files)?;
    }
    Ok(files)
}

pub fn generate() -> Result<BTreeMap<String, String>, GenError> {
    let all = crate::modules::ts_exports();
    check_declarations(&all)?;
    let tmp = std::env::temp_dir().join(format!(
        "tessera-gen-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or_default()
    ));
    fs::create_dir_all(&tmp).map_err(io_err(&tmp))?;
    let result = export_into(&tmp, &all).and_then(|()| read_ts_files(&tmp));
    let _ = fs::remove_dir_all(&tmp);
    let mut files = result?;
    let cfg = Config::new();
    files.insert("ToolMap.ts".to_owned(), tool_map_ts(&all, &cfg));
    files.insert("TopicMap.ts".to_owned(), topic_map_ts(&all, &cfg));
    files.insert(INDICATORS_TS.to_owned(), indicators_ts());
    files.insert(THEME_TS.to_owned(), theme_ts());
    let index = index_ts(&files);
    files.insert("index.ts".to_owned(), index);
    Ok(files)
}

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Staleness {
    pub missing: Vec<String>,
    pub changed: Vec<String>,
    pub extra: Vec<String>,
}

impl Staleness {
    pub fn is_fresh(&self) -> bool {
        self.missing.is_empty() && self.changed.is_empty() && self.extra.is_empty()
    }
}

pub fn check(dir: &Path) -> Result<Staleness, GenError> {
    let generated = generate()?;
    let existing = read_ts_files(dir)?;
    let mut s = Staleness::default();
    for (name, content) in &generated {
        match existing.get(name) {
            None => s.missing.push(name.clone()),
            Some(c) if c != content => s.changed.push(name.clone()),
            _ => {}
        }
    }
    for name in existing.keys() {
        if !generated.contains_key(name) {
            s.extra.push(name.clone());
        }
    }
    Ok(s)
}

pub fn write(dir: &Path) -> Result<Staleness, GenError> {
    let staleness = check(dir)?;
    let generated = generate()?;
    fs::create_dir_all(dir).map_err(io_err(dir))?;
    for name in &staleness.extra {
        let path = dir.join(name);
        fs::remove_file(&path).map_err(io_err(&path))?;
    }
    for name in staleness.missing.iter().chain(&staleness.changed) {
        let path = dir.join(name);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(io_err(parent))?;
        }
        fs::write(&path, &generated[name]).map_err(io_err(&path))?;
    }
    Ok(staleness)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_covers_the_contract() {
        let files = generate().unwrap();
        for name in [
            "ToolDescriptor.ts",
            "ToolResult.ts",
            "AgentEvent.ts",
            "CompactBar.ts",
            "HelloResult.ts",
            "Quote.ts",
            "Layout.ts",
            "ToolMap.ts",
            "TopicMap.ts",
            "indicators.ts",
            "index.ts",
        ] {
            assert!(files.contains_key(name), "{name} not generated");
        }
        assert!(
            files["CompactBar.ts"]
                .contains("[number, number, number, number, number, number, number]")
        );
        assert!(files["Timestamp.ts"].contains("number"));
        assert!(files["index.ts"].contains("export type { ToolResult } from \"./ToolResult\";"));
        assert!(files.contains_key("serde_json/JsonValue.ts"));
        assert!(files["indicators.ts"].contains("\"kind\": \"rsi\""));
        assert!(
            files["index.ts"]
                .contains("export { INDICATOR_SPECS, COLOR_SWATCHES } from \"./indicators\";")
        );
        assert!(!files["index.ts"].contains("export type { indicators }"));
        assert!(
            files["index.ts"]
                .contains("export type { JsonValue } from \"./serde_json/JsonValue\";")
        );
    }

    #[test]
    fn generated_bindings_are_fresh() {
        let dir = default_out_dir();
        let s = check(&dir).unwrap();
        assert!(
            s.is_fresh(),
            "TypeScript bindings in {} are stale ({s:?}). Run: bun run gen",
            dir.display()
        );
    }
}
